package config

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"text/template"

	"github.com/spf13/viper"

	"github.com/mamersfo/neo/internal/libdir"
)

// ErrAlreadyInitialized is returned by Init when neo/neo.toml exists and
// force is false.
var ErrAlreadyInitialized = errors.New("neo project already initialized")

// ErrNotAProject is returned by FindRoot when no neo/neo.toml is found walking up.
var ErrNotAProject = errors.New("not a neo project (no neo/neo.toml found)")

// NeoConfig holds the [neo] table: Docker image + connection details.
// Password is generated on `neo init` (decided 2026-10-10), stored in neo.toml,
// printed once on `start` (Supabase-like).
type NeoConfig struct {
	Image    string `mapstructure:"image"`
	BoltPort int    `mapstructure:"bolt_port"`
	HTTPPort int    `mapstructure:"http_port"`
	User     string `mapstructure:"user"`
	Password string `mapstructure:"password"`
}

// MigrationsConfig holds the [migrations] table.
type MigrationsConfig struct {
	Dir string `mapstructure:"dir"`
}

// Config is the full neo/neo.toml document.
type Config struct {
	Neo        NeoConfig        `mapstructure:"neo"`
	Migrations MigrationsConfig `mapstructure:"migrations"`
}

// Defaults (decided 2026-10-10): LTS exact pin, standard ports.
const (
	DefaultImage    = "neo4j:5.26"
	DefaultBoltPort = 7687
	DefaultHTTPPort = 7474
	DefaultUser     = "neo4j"
	DefaultMigDir   = "migrations"
)

// tomlTemplate is the compiled-in copy of neo/lib/neo.toml.tmpl (go:embed
// cannot reach ../../, so a drift test pins them equal). A same-named file
// in libdir.Dir() (co-located lib/ or $NEO_LIB_DIR) overrides it at runtime.
const tomlTemplate = `# neo configuration — safe to commit, except password is a local secret.
# Generated by 'neo init'. Image pinned to LTS; override for 2025.x testing.
# Rendered with the project Config (.Neo fields, .Migrations.Dir).

[neo]
image = "{{.Neo.Image}}"
bolt_port = {{.Neo.BoltPort}}
http_port = {{.Neo.HTTPPort}}
user = "{{.Neo.User}}"
password = "{{.Neo.Password}}"

[migrations]
dir = "{{.Migrations.Dir}}"
`

const seedPlaceholder = `// neo seed data — runs after 'neo db reset' (unless --no-seed).
// Add your seed Cypher here, e.g.:
// MERGE (p:Person {name: "Ada"}) RETURN p;
`

// GeneratePassword returns a 32-char hex secret (16 random bytes).
// Hex avoids TOML quoting issues; 32 chars exceeds Neo4j's 8-char minimum.
func GeneratePassword() (string, error) {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", fmt.Errorf("generate password: %w", err)
	}
	return hex.EncodeToString(b[:]), nil
}

// DefaultConfig returns a Config with LTS defaults and the given password.
func DefaultConfig(password string) *Config {
	return &Config{
		Neo: NeoConfig{
			Image:    DefaultImage,
			BoltPort: DefaultBoltPort,
			HTTPPort: DefaultHTTPPort,
			User:     DefaultUser,
			Password: password,
		},
		Migrations: MigrationsConfig{Dir: DefaultMigDir},
	}
}

func neoDir(root string) string   { return filepath.Join(root, "neo") }
func tomlPath(root string) string { return filepath.Join(root, "neo", "neo.toml") }
func migrationsDir(root, dir string) string {
	if filepath.IsAbs(dir) {
		return dir
	}
	return filepath.Join(root, "neo", dir)
}

// Init creates a neo project in targetDir (idempotent unless force).
// Returns the project root (abs path). Files: neo/neo.toml (0600, secret),
// neo/migrations/.gitkeep, neo/seed.cypher placeholder (unless present).
func Init(targetDir string, force bool) (string, error) {
	abs, err := filepath.Abs(targetDir)
	if err != nil {
		return "", fmt.Errorf("resolve dir: %w", err)
	}
	toml := tomlPath(abs)
	if _, err := os.Stat(toml); err == nil && !force {
		return "", fmt.Errorf("%w: %s (use --force to overwrite)", ErrAlreadyInitialized, toml)
	}

	mig := migrationsDir(abs, DefaultMigDir)
	if err := os.MkdirAll(mig, 0o755); err != nil {
		return "", fmt.Errorf("create migrations dir: %w", err)
	}

	password, err := GeneratePassword()
	if err != nil {
		return "", err
	}
	cfg := DefaultConfig(password)
	if err := writeTOML(toml, cfg); err != nil {
		return "", err
	}

	seed := filepath.Join(neoDir(abs), "seed.cypher")
	if _, err := os.Stat(seed); errors.Is(err, os.ErrNotExist) || force {
		if err := os.WriteFile(seed, []byte(seedPlaceholder), 0o644); err != nil {
			return "", fmt.Errorf("write seed.cypher: %w", err)
		}
	}

	// Keep empty migrations dir committable.
	entries, err := os.ReadDir(mig)
	if err != nil {
		return "", fmt.Errorf("read migrations dir: %w", err)
	}
	if len(entries) == 0 {
		if err := os.WriteFile(filepath.Join(mig, ".gitkeep"), []byte{}, 0o644); err != nil {
			return "", fmt.Errorf("write .gitkeep: %w", err)
		}
	}

	return abs, nil
}

func loadTomlTemplate() (*template.Template, error) {
	if b, ok := libdir.ReadFile("neo.toml.tmpl"); ok {
		return template.New("neo.toml").Parse(string(b))
	}
	return template.New("neo.toml").Parse(tomlTemplate)
}

func writeTOML(path string, cfg *Config) error {
	t, err := loadTomlTemplate()
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	defer f.Close()
	if err := t.Execute(f, cfg); err != nil {
		return fmt.Errorf("render %s: %w", path, err)
	}
	return nil
}

// FindRoot walks up from startDir looking for neo/neo.toml, like git.
// Returns the project root (dir containing neo/).
func FindRoot(startDir string) (string, error) {
	abs, err := filepath.Abs(startDir)
	if err != nil {
		return "", fmt.Errorf("resolve dir: %w", err)
	}
	for {
		if _, err := os.Stat(tomlPath(abs)); err == nil {
			return abs, nil
		}
		parent := filepath.Dir(abs)
		if parent == abs {
			return "", ErrNotAProject
		}
		abs = parent
	}
}

// Load reads and validates neo/neo.toml under root.
func Load(root string) (*Config, error) {
	v := viper.New()
	v.SetConfigFile(tomlPath(root))
	v.SetConfigType("toml")
	if err := v.ReadInConfig(); err != nil {
		return nil, fmt.Errorf("read %s: %w", tomlPath(root), err)
	}
	var cfg Config
	if err := v.Unmarshal(&cfg); err != nil {
		return nil, fmt.Errorf("parse %s: %w", tomlPath(root), err)
	}
	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	return &cfg, nil
}

// Validate checks required fields and sane ports.
func (c *Config) Validate() error {
	if c.Neo.Image == "" {
		return errors.New("config: [neo] image is required")
	}
	if c.Neo.BoltPort < 1 || c.Neo.BoltPort > 65535 {
		return fmt.Errorf("config: [neo] bolt_port %d out of range", c.Neo.BoltPort)
	}
	if c.Neo.HTTPPort < 1 || c.Neo.HTTPPort > 65535 {
		return fmt.Errorf("config: [neo] http_port %d out of range", c.Neo.HTTPPort)
	}
	if c.Neo.User == "" {
		return errors.New("config: [neo] user is required")
	}
	if len(c.Neo.Password) < 8 {
		return errors.New("config: [neo] password must be at least 8 characters (Neo4j minimum)")
	}
	if c.Migrations.Dir == "" {
		return errors.New("config: [migrations] dir is required")
	}
	return nil
}

// MigrationsPath returns the abs migrations dir for a loaded project.
func (c *Config) MigrationsPath(root string) string {
	return migrationsDir(root, c.Migrations.Dir)
}
